MANCOLOK: Cara Lain Menangkap Ikan di Malam Hari

Kalau menangkap ikan dengan pancingan, jala, atau dengan tembak ikan. sudah biasa terlihat dan terdengar, Tapi di pesisir Simeulue, ada cara yang jauh berbeda. Cara yang bergerak justru saat malam mulai pekat.

Di sini, orang menyebutnya **Mancolok**.

Tidak perlu perahu mesin. Cukup perahu dayung kayu yang melaju pelan, sebuah senter di tangan atau yang diikat di kepala, dan sebuah tangguk dengan gagang panjang. 

Dengan peralatan sesederhana itu, warga menyisir laut mencari ikan, udang, kepiting, bahkan kadang beruntung menemukan lahok, lobster laut yang harganya lumayan tinggi.

Membaca Alam Sebelum Turun

Mancolok tidak bisa dilakukan sembarang malam. Ada waktu yang ditunggu.

Air harus dalam kondisi yang pas, tidak terlalu surut dan tidak terlalu pasang naik. Bulan pun sebaiknya tidak terlalu terang. Justru saat gelap gulita, saat bulan mati, ikan-ikan di tepian seperti tertidur. Diam di sela batu, di bawah akar bakau, atau di pasir dangkal. Cahaya senter yang menyorot tiba-tiba membuat mereka kaku sesaat. Di detik itulah tangguk bergerak perlahan, menangkap tanpa banyak perlawanan.

Perjalanan menyisir pinggiran hutan bakau atau tepian dermaga pada malam seperti itu hampir selalu memuaskan. Hasilnya bukan hanya cukup untuk lauk di rumah, tapi juga bisa dijual. Lumayan, jlintum untuk menambah cuan harian. Apalagi kalau yang nyangkut itu lobster atau kepiting bakau ukuran jumbo.

Di pesisir yang berombak pada malam hari, selain ikan dan lobster, warga juga biasa berburu si'ie. Dalam bahasa lokal Sinabang, itu sebutan untuk sejenis kerang kecil yang hidup bergerombol di sela karang dan pasir. Dikumpulkan satu-satu, rasanya manis sekali kalau dimasak.

Kearifan Lama dari Teluk Sinabang

Ini bukan tradisi baru. Kearifan lokal ini sudah ada sejak saya masih kanak-kanak, melihat lampu-lampu senter bergerak seperti kunang-kunang di sepanjang Teluk Sinabang. Sampai hari ini, tradisi itu masih tetap hidup.

Di warung kopi, cerita Mancolok selalu seru. Seorang kawan bercerita semalam dapat kepiting jumbo sebesar piring, yang lain bersua cumi yang menyemprotkan tinta hitam saat tertangkap. Gelak tawa dan kehebohan itu menjadi bagian dari keseruannya.

Saya sendiri pernah ikut turun. Kami tidak pakai perahu, hanya berjalan kaki menyisir tanaman bakau di pinggir Sungai Panter. Malam itu kami dapat ikan marang, udang-udang segar, dan kepiting kecil-kecil. Pulangnya langsung dimasak jadi mie ala lokal, rasanya mantap sekali karena masih sangat segar.

Jangan Turun Tanpa Persiapan

Meski terlihat sederhana, Mancolok butuh persiapan. Tidak bisa asal berangkat.

1. Lotion anti nyamuk: Wajib, karena kita akan masuk ke area bakau.
2. Senter yang terang dan baterai penuh: Ini adalah senjata utama. Ada yang pakai senter tangan, ada yang pakai senter kepala biar kedua tangan bebas.
3. Parang atau pisau kecil: Sekadar pegangan untuk memotong rumput atau ranting yang menghalangi jalan.
4. Sepatu karet tahan air: Untuk melindungi kaki dari batu tajam, cangkang kerang, atau hewan berbisa.
5. Tangguk bergagang panjang: Supaya bisa menjangkau ikan yang agak jauh tanpa harus membuat banyak gerakan air.

Menurut pengalaman, musim hujan bukan waktu yang cocok. Air jadi keruh dan beriak, cahaya senter tidak tembus. Mancolok butuh air yang tenang dan suasana alam yang cerah.

Pada akhirnya, Mancolok lebih dari sekadar mencari ikan. Ini adalah cara warga mengisi malam-malam tanpa kegiatan, bahkan bagi sebagian orang sudah menjadi mata pencaharian tetap. Ini juga pengingat bahwa laut Simeulue itu sangat bersahabat. Rezekinya bisa dipetik di mana saja, tidak harus pergi jauh ke tengah laut dalam. Di pinggiran bakau dan dermaga pun, laut sudah memberikan potensi yang luar biasa.
